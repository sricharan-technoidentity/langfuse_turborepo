"""Assembles the self-contained Kiro Crew app folder apps/deck-forge/dist/deck-forge.

The gateway copies the install source, so everything the backend imports from the monorepo is vendored:
  backend/deck_forge_backend   <- apps/deck-forge/backend/src
  backend/repo_langfuse        <- packages/infra/langfuse-python/src      (unchanged)
  backend/repo_observability   <- packages/observability/python/src       (unchanged)
  backend/repo_deck_renderer   <- packages/deck-renderer/src
Third-party deps (python-pptx, langfuse + its OpenTelemetry deps) go in requirements.txt; the gateway
pip-installs them with --target on enable."""
import hashlib, json, shutil
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
ROOT = APP.parents[1]
OUT = APP / "dist" / "deck-forge"
VENDOR = {
    "deck_forge_backend": APP / "backend/src/deck_forge_backend",
    "repo_langfuse": ROOT / "packages/infra/langfuse-python/src/repo_langfuse",
    "repo_observability": ROOT / "packages/observability/python/src/repo_observability",
    "repo_deck_renderer": ROOT / "packages/deck-renderer/src/repo_deck_renderer",
}
REQUIREMENTS = "python-pptx==1.0.2\nlangfuse>=5.0.4,<5.1\n"
SHIM = '''"""Kiro Crew entry point (app.json backend.entryPoint). Generated by scripts/assemble.py."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # vendored workspace packages win

from deck_forge_backend.server import main

if __name__ == "__main__":
    main()
'''
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc")


def digest(d: Path) -> str:
    h = hashlib.sha256()
    for f in sorted(p for p in d.rglob("*") if p.is_file() and "__pycache__" not in p.parts):
        h.update(f.relative_to(d).as_posix().encode()); h.update(f.read_bytes())
    return h.hexdigest()[:16]


def main() -> None:
    if OUT.exists(): shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    manifest = json.loads((APP / "app.json").read_text())
    pkg = json.loads((APP / "package.json").read_text())
    assert manifest["name"] == "deck-forge" and manifest["version"] == pkg["version"], "app.json/package.json version mismatch"
    shutil.copy2(APP / "app.json", OUT / "app.json")
    for d in ("agents", "skills", "samples"):
        shutil.copytree(APP / d, OUT / d, ignore=IGNORE)
    shutil.copy2(APP / "README.md", OUT / "README.md")
    (OUT / "requirements.txt").write_text(REQUIREMENTS)
    ui = APP / "ui/dist/index.mjs"
    assert ui.is_file(), "run the @repo/deck-forge-ui build first (turbo does: ^build)"
    (OUT / "ui/dist").mkdir(parents=True); shutil.copy2(ui, OUT / "ui/dist/index.mjs")
    be = OUT / "backend"; be.mkdir()
    (be / "server.py").write_text(SHIM)
    lines = []
    for name, src in VENDOR.items():
        shutil.copytree(src, be / name, ignore=IGNORE)
        lines.append(f"{name}\t{src.relative_to(ROOT)}\tsha256:{digest(src)}")
    (be / "VENDORED.txt").write_text("\n".join(lines) + "\n")
    print(f"assembled {OUT} (v{manifest['version']})")


if __name__ == "__main__":
    main()
